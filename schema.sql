grant execute on function public.set_noirave_timeout(uuid,text,integer,boolean) to authenticated;

create or replace function public.enforce_noirave_chat_controls()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_enabled boolean; v_until timestamptz; v_user uuid;
begin
  if tg_table_name='posts' and new.kind<>'announcement' then return new; end if;
  v_user:=case when tg_table_name='messages' then new.user_id when tg_table_name='direct_messages' then new.sender_id else new.user_id end;
  if public.is_noirave_ceo() then return new; end if;
  if tg_table_name='posts' then
    select announcements_enabled into v_enabled from public.noirave_controls where id=1;
    if coalesce(v_enabled,true)=false then raise exception 'Announcements are temporarily disabled by NoiRave'; end if;
    select announce_disabled_until into v_until from public.user_restrictions where user_id=v_user;
    if v_until>now() then raise exception 'Your announcement access is paused until %',v_until; end if;
  else
    select chat_enabled into v_enabled from public.noirave_controls where id=1;
    if coalesce(v_enabled,true)=false then raise exception 'Chat is temporarily disabled by NoiRave'; end if;
    select chat_disabled_until into v_until from public.user_restrictions where user_id=v_user;
    if v_until>now() then raise exception 'Your chat access is paused until %',v_until; end if;
  end if;
  return new;
end;
$$;
drop trigger if exists enforce_noirave_room_control on public.messages;
