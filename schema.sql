create or replace function public.set_noirave_timeout(p_user_id uuid,p_area text,p_hours integer,p_disable boolean)
returns timestamptz language plpgsql security definer set search_path = '' as $$
declare v_until timestamptz;
begin
  if not public.is_noirave_ceo() then raise exception 'CEO access required'; end if;
  if p_area not in ('chat','announcements') then raise exception 'Choose chat or announcements'; end if;
  if p_disable and (p_hours<1 or p_hours>4) then raise exception 'Timeouts must be from 1 to 4 hours'; end if;
  v_until:=case when p_disable then now()+pg_catalog.make_interval(hours=>p_hours) else null end;
  insert into public.user_restrictions(user_id,chat_disabled_until,announce_disabled_until,updated_at,updated_by)
    values(p_user_id,case when p_area='chat' then v_until end,case when p_area='announcements' then v_until end,now(),auth.uid())
  on conflict(user_id) do update set
    chat_disabled_until=case when p_area='chat' then v_until else public.user_restrictions.chat_disabled_until end,
    announce_disabled_until=case when p_area='announcements' then v_until else public.user_restrictions.announce_disabled_until end,
    updated_at=now(),updated_by=auth.uid();
  return v_until;
end;
$$;
