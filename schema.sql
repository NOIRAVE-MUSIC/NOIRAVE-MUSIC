create or replace function public.is_conversation_member(p_conversation_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.conversation_members cm
    where cm.conversation_id = p_conversation_id and cm.user_id = (select auth.uid())
  );
$$;
revoke execute on function public.is_conversation_member(uuid) from public, anon;
grant execute on function public.is_conversation_member(uuid) to authenticated;

create or replace function public.create_direct_conversation(p_other_user uuid)
returns uuid language plpgsql security definer set search_path = '' as $$
declare
  v_user uuid := auth.uid();
  v_conversation uuid;
begin
  if v_user is null then raise exception 'Sign in is required'; end if;
  if p_other_user is null or p_other_user = v_user then raise exception 'Choose another member'; end if;
  if not exists (select 1 from auth.users u where u.id = p_other_user) then raise exception 'Member not found'; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(least(v_user::text,p_other_user::text)||':'||greatest(v_user::text,p_other_user::text),0));

  select c.id into v_conversation
  from public.conversations c
  where exists (select 1 from public.conversation_members a where a.conversation_id=c.id and a.user_id=v_user)
    and exists (select 1 from public.conversation_members b where b.conversation_id=c.id and b.user_id=p_other_user)
    and (select count(*) from public.conversation_members m where m.conversation_id=c.id)=2
  order by c.created_at limit 1;

  if v_conversation is null then
    insert into public.conversations(created_by) values(v_user) returning id into v_conversation;
    insert into public.conversation_members(conversation_id,user_id)
      values(v_conversation,v_user),(v_conversation,p_other_user);
  end if;
  return v_conversation;
end;
$$;
revoke execute on function public.create_direct_conversation(uuid) from public, anon;
grant execute on function public.create_direct_conversation(uuid) to authenticated;

