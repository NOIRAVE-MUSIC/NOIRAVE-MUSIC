drop trigger if exists enforce_noirave_private_control on public.direct_messages;
create trigger enforce_noirave_private_control before insert on public.direct_messages for each row execute function public.enforce_noirave_chat_controls();
drop trigger if exists enforce_noirave_announcement_control on public.posts;
create trigger enforce_noirave_announcement_control before insert on public.posts for each row execute function public.enforce_noirave_chat_controls();

