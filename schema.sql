create or replace function public.normalize_noirave_language(p_text text)
returns text language plpgsql immutable set search_path = '' as $$
declare v text := lower(coalesce(p_text,''));
begin
  v:=replace(v,'0','o'); v:=replace(v,'1','i'); v:=replace(v,'3','e');
  v:=replace(v,'4','a'); v:=replace(v,'5','s'); v:=replace(v,'7','t');
  v:=replace(v,'@','a'); v:=replace(v,'$','s'); v:=replace(v,'!','i');
  v:=replace(v,'а','a'); v:=replace(v,'е','e'); v:=replace(v,'о','o');
  v:=replace(v,'р','p'); v:=replace(v,'с','c'); v:=replace(v,'х','x');
  v:=replace(v,'у','y'); v:=replace(v,'і','i'); v:=replace(v,'ј','j');
  v:=regexp_replace(v,'[^[:alnum:]]+',' ','g');
  v:=regexp_replace(v,'(.)\1{2,}','\1\1','g');
  return btrim(v);
end;
$$;
create or replace function public.reject_blocked_noirave_language()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_content text; v_normalized text; v_term text;
begin
  if tg_table_name='posts' then v_content:=coalesce(new.title,'')||' '||coalesce(new.description,'');
  elsif tg_table_name='messages' or tg_table_name='direct_messages' then v_content:=coalesce(new.body,'');
  elsif tg_table_name='profiles' then v_content:=coalesce(new.display_name,'')||' '||coalesce(new.bio,'')||' '||coalesce(new.favorite_genres,'')||' '||coalesce(new.custom_status,'')||' '||coalesce(new.profile_note,'');
  else return new; end if;
  v_normalized:=public.normalize_noirave_language(v_content);
  select term into v_term from public.blocked_language_terms
    where enabled and v_normalized ~ ('(^|[^[:alnum:]])'||
      regexp_replace(public.normalize_noirave_language(term),'([[:alnum:]])','\1[^[:alnum:]]*','g')||
      '($|[^[:alnum:]])') limit 1;
  if v_term is not null then raise exception 'This text contains language blocked by NoiRave. Please edit it and try again.'; end if;
  return new;
end;
$$;
