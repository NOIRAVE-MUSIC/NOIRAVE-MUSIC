create or replace function public.review_verification_request(p_request_id uuid,p_approve boolean)
returns void language plpgsql security definer set search_path = '' as $$
declare v_user uuid; v_status text;
begin
  if not public.is_noirave_ceo() then raise exception 'CEO access required'; end if;
  v_status := case when p_approve then 'approved' else 'rejected' end;
  update public.verification_requests set status=v_status,reviewed_at=now(),reviewed_by=auth.uid()
    where id=p_request_id and status='pending' returning user_id into v_user;
  if v_user is null then raise exception 'Pending verification request not found'; end if;
  insert into public.profiles(user_id,display_name,is_verified)
    select u.id,left(coalesce(nullif(u.raw_user_meta_data->>'display_name',''),split_part(u.email,'@',1)),40),p_approve
    from auth.users u where u.id=v_user
    on conflict(user_id) do update set is_verified=excluded.is_verified,updated_at=now();
end;
$$;
revoke execute on function public.review_verification_request(uuid,boolean) from public, anon;
grant execute on function public.review_verification_request(uuid,boolean) to authenticated;



