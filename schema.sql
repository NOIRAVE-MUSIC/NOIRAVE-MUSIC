returns uuid language plpgsql security definer set search_path = '' as $$
declare v_user uuid:=auth.uid(); v_conversation uuid; v_people uuid[];
begin
  if v_user is null then raise exception 'Sign in is required'; end if;
  if char_length(btrim(coalesce(p_title,'')))<1 or char_length(btrim(p_title))>80 then raise exception 'Group name must be 1 to 80 characters'; end if;
  select array_agg(person order by person) into v_people
    from (select distinct person from unnest(coalesce(p_participants,'{}'::uuid[])||array[v_user]) person where person is not null) p;
  if cardinality(v_people)<3 then raise exception 'Choose at least two other people for a group chat'; end if;
  if cardinality(v_people)>50 then raise exception 'Group chats can have up to 50 members'; end if;
  if (select count(*) from auth.users where id=any(v_people))<>cardinality(v_people) then raise exception 'One or more members could not be found'; end if;
  insert into public.conversations(created_by,title,is_group) values(v_user,btrim(p_title),true) returning id into v_conversation;
  insert into public.conversation_members(conversation_id,user_id) select v_conversation,person from unnest(v_people) person;
  return v_conversation;
end;
$$;
revoke execute on function public.create_group_conversation(text,uuid[]) from public,anon;
grant execute on function public.create_group_conversation(text,uuid[]) to authenticated;

